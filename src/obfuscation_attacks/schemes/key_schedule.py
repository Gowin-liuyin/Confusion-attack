"""Client-side key schedule for the A+B deployment (protocol §1, §8.1).

The server may see an opaque rotation-group id, never the seed, the root key or
the per-request key. Keys are derived with HKDF-SHA256 from a 256-bit secret
root; the root is generated by :mod:`secrets` unless a test supplies one.

The derived 32-byte HKDF output seeds a deterministic standard-normal vector
(``numpy.random.default_rng``). This keeps the key distribution matching the
encoder's training distribution (``torch.randn`` in the packaged artifact)
while the root stays secret and domain-separated.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets

import numpy as np

_SALT = b"confusionattack/ab-deployment/v1"
_KEY_LEN = 32
_ROOT_LEN = 32


class KeySchedule:
    """Secret root -> per-key-pool-index vector and opaque group id.

    Protocol §8.2: ``epoch`` is rotation metadata, not key identity. A key index
    is reused across rotation epochs (pool cycling); a different key requires a
    different index. The group id therefore identifies the key, while the epoch
    is logged separately.
    """

    def __init__(self, root_key: bytes | None = None) -> None:
        root = secrets.token_bytes(_ROOT_LEN) if root_key is None else bytes(root_key)
        if len(root) != _ROOT_LEN:
            raise ValueError(
                f"root_key must be exactly {_ROOT_LEN} bytes (256 bits); got {len(root)}"
            )
        self._root = root
        self._next = 0

    def _info(self, index: int, epoch: int = 0) -> bytes:
        del epoch  # rotation metadata, never key identity (protocol §8.2)
        return f"request-key|index={int(index)}".encode("ascii")

    def _prk(self) -> bytes:
        return hmac.new(_SALT, self._root, hashlib.sha256).digest()

    def derive(self, index: int, epoch: int = 0) -> np.ndarray:
        """HKDF-SHA256 expand from the key-pool index (epoch is metadata only)."""
        prk = self._prk()
        info = self._info(index, epoch)
        okm = b""
        block = b""
        counter = 1
        while len(okm) < _KEY_LEN:
            block = hmac.new(prk, block + info + bytes([counter]), hashlib.sha256).digest()
            okm += block
            counter += 1
        raw = okm[:_KEY_LEN]
        rng = np.random.default_rng(int.from_bytes(raw, "big"))
        return rng.standard_normal(_KEY_LEN).astype(np.float32)

    def group_id(self, index: int, epoch: int = 0) -> str:
        """Opaque id for one key; stable across rotation epochs, not invertible."""
        mac = hmac.new(
            self._root, b"group-id|" + self._info(index, epoch), hashlib.sha256
        ).hexdigest()
        return "g-" + mac[:32]

    def next_index(self) -> int:
        index = self._next
        self._next += 1
        return index

    def public_metadata(self, index: int, epoch: int = 0) -> dict:
        """Only what the server may log: the opaque group id and the epoch."""
        return {"group_id": self.group_id(index, epoch), "epoch": int(epoch)}

    def __repr__(self) -> str:
        return f"KeySchedule(root=<redacted>, bits={_ROOT_LEN * 8})"

    __str__ = __repr__
